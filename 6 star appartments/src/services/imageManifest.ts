/**
 * Returns safe encoded URL path for any project image.
 * Ensures consistent leading slash and properly encodes spaces and URI symbols (+, parentheses).
 */
export function getSafeImageUrl(relativePath: string): string {
  if (!relativePath) return '';
  if (relativePath.startsWith('http://') || relativePath.startsWith('https://') || relativePath.startsWith('data:')) {
    return relativePath;
  }
  // Remove any leading ./ or /
  const cleaned = relativePath.replace(/^(\.\/|\/)/, '');
  const encodedPath = cleaned
    .split('/')
    .map(segment => encodeURIComponent(decodeURIComponent(segment)).replace(/%2B/gi, '+'))
    .join('/');
  return '/' + encodedPath;
}

